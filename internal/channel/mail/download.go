package mail

import (
	"bytes"
	"context"
	"fmt"
	"io"

	"github.com/reyer3/bunker-go/internal/core"

	"github.com/emersion/go-imap/v2"
	gomessage "github.com/emersion/go-message"
	gomail "github.com/emersion/go-message/mail"
)

// DownloadAttachment implements core.AttachmentDownloader: it re-fetches
// item's raw message by UID over IMAP (the same BODY.PEEK round trip
// Fetch makes, so this never marks anything \Seen either) and returns
// the index-th attachment part's raw bytes. Mail keeps no attachment
// bytes of its own between calls, so every download re-reads the source
// message from the server.
func (a *Adapter) DownloadAttachment(ctx context.Context, item core.Item, index int) (io.ReadCloser, error) {
	if index < 0 || index >= len(item.Attachments) {
		return nil, fmt.Errorf("mail: download %s: attachment index %d out of range: %w", item.ID, index, core.ErrNotFound)
	}

	account, folder, uidValidity, uid, err := parseItemID(item.ID)
	if err != nil {
		return nil, err
	}
	if account != a.cfg.Name {
		return nil, fmt.Errorf("mail: item %q is not for account %q: %w", item.ID, a.cfg.Name, core.ErrNotFound)
	}

	client, err := a.dial(ctx, a.cfg, a.passwordSource, a.tokenSource, nil)
	if err != nil {
		return nil, fmt.Errorf("mail: download %s: %w", item.ID, err)
	}
	defer client.Close()

	folders, err := discoverFolders(ctx, client, a.cfg)
	if err != nil {
		return nil, fmt.Errorf("mail: download %s: %w", item.ID, err)
	}
	mailbox := mailboxFor(folders, folder)

	mbox, err := client.Select(mailbox, &imap.SelectOptions{ReadOnly: true}).Wait()
	if err != nil {
		return nil, fmt.Errorf("mail: download %s: select %s: %w", item.ID, mailbox, err)
	}
	if mbox.UIDValidity != uidValidity {
		return nil, fmt.Errorf("mail: download %s: mailbox UIDVALIDITY changed (%d != %d): %w", item.ID, mbox.UIDValidity, uidValidity, core.ErrNotFound)
	}

	fetchOptions := &imap.FetchOptions{
		UID:         true,
		BodySection: []*imap.FetchItemBodySection{{Peek: true}},
	}
	messages, err := client.Fetch(imap.UIDSetNum(uid), fetchOptions).Collect()
	if err != nil {
		return nil, fmt.Errorf("mail: download %s: %w", item.ID, err)
	}
	if len(messages) == 0 {
		return nil, fmt.Errorf("mail: download %s: %w", item.ID, core.ErrNotFound)
	}

	var raw []byte
	for _, section := range messages[0].BodySection {
		raw = section.Bytes
	}
	if len(raw) == 0 {
		return nil, fmt.Errorf("mail: download %s: empty message body", item.ID)
	}

	kinds := make([]bool, len(item.Attachments))
	for i, row := range item.Attachments {
		kinds[i] = row.Inline
	}
	data, err := attachmentPartAt(raw, kinds, index)
	if err != nil {
		return nil, fmt.Errorf("mail: download %s: %w", item.ID, err)
	}
	return io.NopCloser(bytes.NewReader(data)), nil
}

// attachmentPartAt walks raw's MIME parts in exactly the order walkMessage
// (fetch.go) builds Item.Attachments from and lands on the part that the
// stored row `index` addresses, read out of the store as usual.
//
// kinds[i] is the Inline flag of the i-th stored attachment row, i.e. what
// the uploader counted when the item was stored. Alignment walks the
// enumeration consuming, row by row, the first not-yet-consumed part whose
// kind matches the row's: rows generated by the current walkMessage find
// each part in order, and rows stored before inline images existed (they
// only counted attachment parts) keep addressing the same paperclip part
// they always did, now skipped over the CID images ahead of them.
func attachmentPartAt(raw []byte, kinds []bool, index int) ([]byte, error) {
	if index < 0 || index >= len(kinds) {
		return nil, fmt.Errorf("attachment index %d not found (%d rows): %w", index, len(kinds), core.ErrNotFound)
	}
	reader, err := gomail.CreateReader(bytes.NewReader(raw))
	if err != nil && !gomessage.IsUnknownCharset(err) {
		return nil, fmt.Errorf("read message: %w", err)
	}
	defer reader.Close()

	n := 0
	for {
		part, err := reader.NextPart()
		if err == io.EOF {
			break
		}
		if err != nil && !gomessage.IsUnknownCharset(err) {
			return nil, fmt.Errorf("read part: %w", err)
		}
		keep := false
		switch h := part.Header.(type) {
		case *gomail.AttachmentHeader:
			keep = true
		case *gomail.InlineHeader:
			contentType, _, _ := h.ContentType()
			keep = isInlineImage(contentType)
		}
		if !keep {
			continue
		}
		// Consume only the part the row at n counted: a row generated by
		// the current walk matches its own kind; a legacy row
		// (Inline=false) skips over the CID images the modern
		// enumeration would have counted.
		isInline := false
		if _, ok := part.Header.(*gomail.InlineHeader); ok {
			isInline = true
		}
		if isInline != kinds[n] {
			continue
		}
		if n == index {
			data, readErr := io.ReadAll(part.Body)
			if readErr != nil {
				return nil, fmt.Errorf("read attachment part: %w", readErr)
			}
			return data, nil
		}
		n++
	}
	return nil, fmt.Errorf("attachment index %d not found (message has %d attachments): %w", index, n, core.ErrNotFound)
}
